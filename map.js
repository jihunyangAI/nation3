function initMap() {
  const s = mapSvg(), pts = new Map();
  let moved = false, startX = 0, startY = 0, pinch = null;
  const pair = () => { const [a, b] = [...pts.values()]; return { d: Math.hypot(a.x - b.x, a.y - b.y) || 1, x: (a.x + b.x) / 2, y: (a.y + b.y) / 2 }; };
  s.addEventListener('pointerdown', e => {
    s.setPointerCapture(e.pointerId);
    pts.set(e.pointerId, { x: e.clientX, y: e.clientY });
    if (pts.size === 1) { moved = false; startX = e.clientX; startY = e.clientY; }
    if (pts.size === 2) { moved = true; pinch = pair(); }
  });
  s.addEventListener('pointermove', e => {
    const p = pts.get(e.pointerId);
    if (!p) return;
    const dx = e.clientX - p.x, dy = e.clientY - p.y;
    p.x = e.clientX; p.y = e.clientY;
    if (pts.size === 2 && pinch) {
      const n = pair(), k = pxPer(), [wx, wy] = toWorld(n.x, n.y);
      V.x -= (n.x - pinch.x) / k; V.y -= (n.y - pinch.y) / k;
      pinch = n.d && pinch.d ? (zoomAt(wx - (n.x - pinch.x) / k, wy - (n.y - pinch.y) / k, n.d / pinch.d), n) : n;
    } else if (pts.size === 1) {
      if (Math.hypot(e.clientX - startX, e.clientY - startY) > 7) moved = true;
      if (moved && V.z > 1.01) { const k = pxPer(); V.x -= dx / k; V.y -= dy / k; applyView(); }
    }
  });
  const end = e => {
    const had = pts.delete(e.pointerId);
    if (pts.size < 2) pinch = null;
    if (!had || e.type !== 'pointerup' || moved || pts.size || !G) return;
    const [x, y] = toWorld(e.clientX, e.clientY), k = pxPer();
    let best = null, bd = 34 / k;
    G.cities.forEach(c => { const d = Math.hypot(c.x - x, c.y - y); if (d < bd) { bd = d; best = c; } });
    if (best) selectCity(best.id);
  };
  s.addEventListener('pointerup', end); s.addEventListener('pointercancel', end);
  s.addEventListener('wheel', e => {
    e.preventDefault();
    const [x, y] = toWorld(e.clientX, e.clientY);
    zoomAt(x, y, e.deltaY < 0 ? 1.2 : 1 / 1.2);
  }, { passive: false });
  s.addEventListener('dblclick', e => { const [x, y] = toWorld(e.clientX, e.clientY); zoomAt(x, y, 1.8); });
  window.addEventListener('resize', () => { if (G) drawOverlay(); });
}

